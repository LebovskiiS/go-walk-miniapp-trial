let page = null; // null — закрыто, "menu" — оглавление, иначе ключ страницы

function menuView() {
  const rows = PAGES.map(
    (p) => `<button class="item link-row" data-act="learning-page" data-page="${p.key}">
      <div class="row"><b>${esc(p.title)}</b><span class="chev">›</span></div></button>`,
  ).join("");
  return `<section class="page"><h2>🎓 Обучение</h2><p class="muted">${esc(INTRO)}</p>
    <div class="card list">${rows}</div></section>`;
}

function pageView(p) {
  const tag = p.ordered ? "ol" : "ul";
  const items = p.steps.map((step) => `<li>${esc(step)}</li>`).join("");
  return `<section class="page"><h2>${esc(p.title)}</h2>
    ${p.lead ? `<p>${esc(p.lead)}</p>` : ""}<${tag} class="steps">${items}</${tag}>
    ${p.note ? `<p class="card">${esc(p.note)}</p>` : ""}
    <button class="btn ghost" data-act="learning-page" data-page="menu">⬅️ Обучение</button></section>`;
}

function view() {
  const current = PAGES.find((p) => p.key === page);
  return current ? pageView(current) : menuView();
}

registerOverlay({
  isOpen: () => page !== null,
  view,
  // «назад» со страницы — в оглавление, из оглавления — в кабинет
  close: () => {
    page = page === "menu" ? null : "menu";
  },
});

registerActions({
  "learning-open": () => {
    page = "menu";
    window.scrollTo(0, 0);
  },
  "learning-page": ({ page: key }) => {
    page = key;
    window.scrollTo(0, 0);
  },
});

